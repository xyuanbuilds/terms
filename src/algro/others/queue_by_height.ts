/**
 * 406. 根据身高重建队列
 * https://leetcode.cn/problems/queue-reconstruction-by-height/description/
 *
 * * 贪心
 *
 * 输入：people = [[7,0],[4,4],[7,1],[5,0],[6,1],[5,2]]
 * 输出：[[5,0],[7,0],[5,2],[6,1],[4,4],[7,1]]
 * 编号为 0 的人身高为 5 ，没有身高更高或者相同的人排在他前面。
 * 编号为 1 的人身高为 7 ，没有身高更高或者相同的人排在他前面。
 * 编号为 2 的人身高为 5 ，有 2 个身高更高或者相同的人排在他前面，即编号为 0 和 1 的人。
 * 编号为 3 的人身高为 6 ，有 1 个身高更高或者相同的人排在他前面，即编号为 1 的人。
 * 编号为 4 的人身高为 4 ，有 4 个身高更高或者相同的人排在他前面，即编号为 0、1、2、3 的人。
 * 编号为 5 的人身高为 7 ，有 1 个身高更高或者相同的人排在他前面，即编号为 1 的人。
 * 因此 [[5,0],[7,0],[5,2],[6,1],[4,4],[7,1]] 是重新构造后的队列。
 *
 * [身高，排在他前面 且 身高 >= 他 的人数]
 *
 * 有两个维度，身高，和前面人数，身高起决定性影响，所以先排身高（高的在前面），再考虑前面人数（少的在前面）
 * 先排序，再插入
 * 贪心的本质是选择每一阶段的局部最优，从而达到全局最优
 */

/**
 * @param {number[][]} people
 * @return {number[][]}
 */
const reconstructQueue = (people: [number, number][]): [number, number][] => {
  const res: [number, number][] = [];

  /** 按照 身高降序，同高 再按照前人 多数升序 */
  /** 因为矮的人插入队前不会影响高的人，所以先排个子更高的人，优先保证高个的合理位置 */
  people.sort((a, b) => (a[0] === b[0] ? a[1] - b[1] : b[0] - a[0]));
  // [[7,0],[7,1],[6,1],[5,0],[5,2],[4,4]]

  /**
   * 高的人优先入队后，矮的根据前面有几个人插入队列
   * 因为高的已经先入队了，所以插入的位置前面肯定都是比当前入队的人 高 或相同 的
   * */
  people.forEach((single) => res.splice(single[1], 0, single));

  return res;
};
